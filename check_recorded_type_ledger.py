"""Compare both actual spatial ledgers and test rejection of mixed input evidence."""

import argparse
import copy
from hashlib import sha256
import json
from pathlib import Path

from opening_missile_flag import recorded_type_ledger
from opening_unit_radii import check


def verify(baseline, candidate, receipt):
    old = json.loads(baseline.read_bytes())
    new = json.loads(candidate.read_bytes())
    report = json.loads(receipt.read_bytes())
    check(len(old)==len(new)==172 and [r['slot'] for r in old]==list(range(172)), 'Opening order')
    for before, after in zip(old, new):
        base_mask, result_mask = (int.from_bytes(bytes.fromhex(r['mask']),'little') for r in (before,after))
        check(base_mask.bit_count()==92 and result_mask.bit_count()==93 and
              result_mask == base_mask | (1<<30) and result_mask^base_mask == 1<<30, 'Unexpected mask')
        check(before['value'] == after['value'] and not (int.from_bytes(bytes.fromhex(after['value']),'little')>>30)&1,
              'Unexpected value at an opening slot')
        check(dict(before,mask=after['mask'],known_bits=93)==after, 'Other fields changed')
    raw = candidate.read_bytes()
    check(sha256(raw).hexdigest()==report['recorded_type_live_radius_ledger']['sha256']
          and recorded_type_ledger(baseline,report)==raw, 'Regenerated bytes differ')
    wrong_flag = copy.deepcopy(report)
    wrong_flag['by_unit'][old[0]['unit']]['missile'] ^= 1
    for invalid, data in ((candidate,report), (baseline,wrong_flag), (baseline,dict(report,build=41810))):
        try:
            recorded_type_ledger(invalid,data)
        except ValueError:
            continue
        raise ValueError('Accepted mismatched evidence')
    return dict(slots=len(new),byte_identical_value_fields=len(new),only_added_mask_bit=30,
                known_bits_before=92,known_bits_after=93,rejected_mixed_inputs=3,
                private_ledger_sha256=sha256(raw).hexdigest())


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    for key in ('baseline','candidate','receipt'):
        parser.add_argument(key,type=Path)
    print(json.dumps(verify(**vars(parser.parse_args())),indent=2))
